@OVERRIDE_STORAGES
class HomeViewTest(TestCase):
    """
    Tests for HomeView (GET /).

    The landing page shows top-5 teams by win%, 3 featured conferences,
    and platform-wide counts (teams, conferences, games).
    """

    def test_status_200(self):
        """Home page should return HTTP 200 for any request."""
        response = self.client.get(reverse('opencourt:home'))
        self.assertEqual(response.status_code, 200)

    def test_correct_template(self):
        """Home page should render the opencourt/home.html template."""
        response = self.client.get(reverse('opencourt:home'))
        self.assertTemplateUsed(response, 'opencourt/home.html')

    def test_empty_database(self):
        """
        Home page should render without errors when the database is empty
        (no teams, conferences, or games). This is the first-run state
        before sync_data has been executed.
        """
        response = self.client.get(reverse('opencourt:home'))
        self.assertEqual(response.status_code, 200)
        self.assertEqual(response.context['total_teams'], 0)
        self.assertEqual(response.context['total_conferences'], 0)
        self.assertEqual(response.context['total_games'], 0)

    def test_top_teams_limited_to_five(self):
        """
        top_teams in context should contain at most 5 teams, even when
        more teams with stats exist in the database.
        """
        conf = _make_conference()
        for i in range(8):
            team = _make_team(
                conference=conf,
                source_id=i,
                school=f'Team{i}',
                mascot=f'Mascot{i}',
                slug=f'team-{i}',
            )
            _make_season_stats(team, wins=20.0 + i, losses=10.0)

        response = self.client.get(reverse('opencourt:home'))
        self.assertLessEqual(len(response.context['top_teams']), 5)

    def test_platform_stats_counts(self):
        """Context should include accurate counts for teams, conferences, games."""
        conf = _make_conference()
        team1 = _make_team(conference=conf, source_id=1, slug='t1', school='T1', mascot='M1')
        team2 = _make_team(conference=conf, source_id=2, slug='t2', school='T2', mascot='M2')
        _make_game(team1, team2)

        response = self.client.get(reverse('opencourt:home'))
        self.assertEqual(response.context['total_teams'], 2)
        self.assertEqual(response.context['total_conferences'], 1)
        self.assertEqual(response.context['total_games'], 1)

