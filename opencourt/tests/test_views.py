# ---------------------------------------------------------------------------
# Static files override
# ---------------------------------------------------------------------------
# In production, settings.py uses CompressedManifestStaticFilesStorage, which
# requires a staticfiles manifest generated by `collectstatic`. The test
# environment skips that step, so template rendering would crash on {% static %}
# tags. We override STORAGES here to use the basic StaticFilesStorage backend
# that doesn't need a manifest. This decorator is applied to every view test
# class below.
OVERRIDE_STORAGES = override_settings(STORAGES={
    'staticfiles': {
        'BACKEND': 'django.contrib.staticfiles.storage.StaticFilesStorage',
    },
})

