# test_views.py — Integration tests for opencourt/views.py.
#
# Tests each view's HTTP response: status code, template used, and key
# context variables. Uses Django's test Client to make real requests
# against the test database — no mocking needed.
#
# Each test class targets one view. Tests create the minimum database
# state needed for the view to render successfully, then assert on the
# response.
#
# These tests hit the real ORM and template engine but NOT the CBBData
# API — views only read from the database, so no API mocking is required.
#
# Note: The predictions model file is not present in the test environment
# by default. Tests for UpcomingView mock make_predictions to avoid
# FileNotFoundError.
#
# Run just these tests:
#   uv run python manage.py test opencourt.tests.test_views

import json
from datetime import date, datetime, timedelta
from unittest.mock import patch

from django.test import TestCase, Client, override_settings
from django.urls import reverse
from django.utils import timezone

# ---------------------------------------------------------------------------
# Static files override
# ---------------------------------------------------------------------------
# In production, settings.py uses CompressedManifestStaticFilesStorage, which
# requires a staticfiles manifest generated by `collectstatic`. The test
# environment skips that step, so template rendering would crash on {% static %}
# tags. We override STORAGES here to use the basic StaticFilesStorage backend
# that doesn't need a manifest. This decorator is applied to every view test
# class below.
OVERRIDE_STORAGES = override_settings(STORAGES={
    'staticfiles': {
        'BACKEND': 'django.contrib.staticfiles.storage.StaticFilesStorage',
    },
})

from opencourt.models import (
    Team, Conference, TeamSeasonStats, Game, GameTeamStats, Ranking,
)

