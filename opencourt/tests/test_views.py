# test_views.py — Integration tests for opencourt/views.py.
#
# Tests each view's HTTP response: status code, template used, and key
# context variables. Uses Django's test Client to make real requests
# against the test database — no mocking needed.
#
# Each test class targets one view. Tests create the minimum database
# state needed for the view to render successfully, then assert on the
# response.
#
# These tests hit the real ORM and template engine but NOT the CBBData
# API — views only read from the database, so no API mocking is required.
#
# Note: The predictions model file is not present in the test environment
# by default. Tests for UpcomingView mock make_predictions to avoid
# FileNotFoundError.
#
# Run just these tests:
#   uv run python manage.py test opencourt.tests.test_views

import json
